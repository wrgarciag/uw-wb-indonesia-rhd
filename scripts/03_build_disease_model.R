  stop("Population projection is missing a sex.", call. = FALSE)

# GBD rates must actually carry RHD signal (not all zero)
if (sum(prev_rhd0) == 0 || sum(ir_rhd0) == 0)
  stop("GBD RHD prevalence/incidence rates are all zero -- check inputs.", call. = FALSE)

# competing-risk headroom at the base year: IR + background <= 1
if (any(ir_rhd0 + oth_mort0 > 1 + 1e-9))
  stop("IR + background mortality exceeds 1 at some age-sex cell.", call. = FALSE)

# --- natural-history / effect / surgery / care sanity --------------------------
# (abcd_nh_build above already validated every natural-history input.)
prob_params <- c(unlist(effects[c("eff_surgery_C_to_D", "eff_surgery_D_to_rhd_death",
                                  "sap_hr_A_to_B_child", "sap_hr_B_to_C_child", "sap_hr_B_to_C_adult", "sap_hr_C_to_D")]),
                 coverage$confirm_completion, coverage$confirm_sensitivity,
                 surgery$frac_C_requiring_surgery, surgery$frac_D_requiring_surgery,
                 surgery$coverage_ref_baseline, surgery$coverage_ref_target,
                 surgery$coverage_up_baseline,  surgery$coverage_up_target,
                 unlist(coverage$care_inputs), coverage$screen_sensitivity,
                 coverage$partial_adherence_relative_protection,
                 unlist(coverage$init[c("diagnosed_share", "on_bpg_share", "ever_screened_share")]))
if (any(!is.finite(prob_params)) || any(prob_params < 0 | prob_params > 1))
  stop("An effect/surgery/care parameter is outside [0,1].", call. = FALSE)
if (any(p_rhd_death[c("A", "B", "C")] != 0) || p_rhd_death[["D"]] <= 0)
  stop("D_only requires p_rhd_death A/B/C == 0 exactly and D > 0.", call. = FALSE)
for (arm in c("ref", "up"))
  if (any(coverage$care_inputs$adherence_good[[arm]] + coverage$care_inputs$adherence_partial[[arm]] > 1 + 1e-12))
    stop("good + partial adherence shares exceed 1 (", arm, " arm).", call. = FALSE)
for (nm in names(coverage$care_inputs))
  if (diff(coverage$care_inputs[[nm]]$ref) != 0)
    stop("Reference-arm care input '", nm, "' must be held flat (baseline == target).", call. = FALSE)
if (coverage$init$on_bpg_share > coverage$init$diagnosed_share)
  stop("Initial on-BPG share exceeds the initial diagnosed share.", call. = FALSE)
if (coverage$screen_age_lo > coverage$screen_age_hi || coverage$screen_age_lo < min(AGES) || coverage$screen_age_hi > max(AGES))
  stop("Screening window must satisfy min(AGES) <= screen_age_lo <= screen_age_hi <= max(AGES).", call. = FALSE)
# reference care applied in calibration == reference arm baseline (one care spec)
abcd_care_schedule(c(lapply(coverage$care_inputs, function(x) x$ref[["baseline"]]),
                     list(surgery = surgery$coverage_ref_baseline, sensitivity = coverage$screen_sensitivity,
                          confirm_completion = coverage$confirm_completion, confirm_sensitivity = coverage$confirm_sensitivity,
                          partial_relative_protection = coverage$partial_adherence_relative_protection,
                          screen_age_lo = coverage$screen_age_lo, screen_age_hi = coverage$screen_age_hi)),
                   1L, AGES, SEXES)                  # validates the care inputs through the engine

# order-of-magnitude anchors vs GBD (base-year rate x base-year population)
rhd_prev_count  <- sum(prev_rhd0 * pop1)
rhd_death_count <- sum(mort_rhd0 * pop1)
all_death_count <- sum(mort_all0 * pop1)
message(sprintf(
  "Data-fed inputs OK | horizon %d-%d | ages %d-%d\n  base-year(%d): RHD prevalence ~ %s | RHD deaths ~ %s | all-cause deaths ~ %s",
  as.integer(min(years)), as.integer(max(years)),
  as.integer(min(AGES)), as.integer(max(AGES)), as.integer(years[1]),
  formatC(round(rhd_prev_count),  format = "d", big.mark = ","),
  formatC(round(rhd_death_count), format = "d", big.mark = ","),
  formatC(round(all_death_count), format = "d", big.mark = ",")))
# sane order-of-magnitude bands for RHD (COUNTRY-settable from 00_run_all.R; the
# wide defaults cover both Indonesia and Uganda). Prevalence and RHD deaths.
RHD_PREV_LO  <- getp("RHD_PREV_LO",  1e5); RHD_PREV_HI  <- getp("RHD_PREV_HI",  1e7)
RHD_DEATH_LO <- getp("RHD_DEATH_LO", 1e3); RHD_DEATH_HI <- getp("RHD_DEATH_HI", 1e5)
if (rhd_prev_count < RHD_PREV_LO || rhd_prev_count > RHD_PREV_HI)
  stop("Base-year RHD prevalence count ", round(rhd_prev_count),
       " is outside the sane band ", RHD_PREV_LO, "-", RHD_PREV_HI, ".", call. = FALSE)
if (rhd_death_count < RHD_DEATH_LO || rhd_death_count > RHD_DEATH_HI)
  stop("Base-year RHD death count ", round(rhd_death_count),
       " is outside the sane band ", RHD_DEATH_LO, "-", RHD_DEATH_HI, ".", call. = FALSE)

